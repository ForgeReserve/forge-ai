// Writes the licences of what libptts_ffi.so is compiled from (scripts/android-ptts.sh): the Rust
// crates that are linked into it for arm64 Android, from `cargo metadata` of the pinned xn-ptts checkout
// with its Cargo.lock. Build scripts and procedural macros run only at build time and are left out.
// Each distinct licence text is given once, with the crates it covers, as phonon-tts's own list does.
//   node scripts/ptts/licenses.ts <xn-ptts checkout> <out.md>
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

interface Pkg {
  id: string;
  name: string;
  version: string;
  license: string | null;
  license_file: string | null;
  manifest_path: string;
  repository: string | null;
  targets: { kind: string[] }[];
}

const [src, out] = process.argv.slice(2);
if (!src || !out) throw new Error('usage: licenses.ts <xn-ptts checkout> <out.md>');
const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', 'aarch64-linux-android', '--manifest-path', join(src, 'Cargo.toml')], { maxBuffer: 256 << 20, encoding: 'utf8' }),
);
const pkgs = new Map<string, Pkg>(meta.packages.map((p: Pkg) => [p.id, p]));
const root = meta.packages.find((p: Pkg) => p.name === 'ptts-ffi');
if (!root) throw new Error('no ptts-ffi in the workspace');

// What is linked: ptts-ffi's normal dependencies for arm64 Android with the features a build of
// ptts-ffi alone turns on (cargo tree), never a proc-macro. (The metadata's own graph has the whole
// workspace's features, which would list the servers' crates too.)
const tree = execFileSync('cargo', ['tree', '--locked', '-p', 'ptts-ffi', '--target', 'aarch64-linux-android', '-e', 'normal', '--prefix', 'none', '-f', '{p}'], { cwd: src, maxBuffer: 64 << 20, encoding: 'utf8' });
const inTree = new Set(tree.split('\n').map((l) => l.replace(/ \(.*$/, '').trim()).filter(Boolean));
const linked = new Set<string>();
for (const [id, p] of pkgs) {
  if (!inTree.has(`${p.name} v${p.version}`)) continue;
  if (p.targets.some((t) => t.kind.includes('proc-macro'))) continue;
  linked.add(id);
}

const texts = new Map<string, { name: string; crates: string[] }>();
const missing: string[] = [];
const label = (file: string) => (/apache/i.test(file) ? 'Apache License 2.0' : /mit/i.test(file) ? 'MIT License' : /unicode/i.test(file) ? 'Unicode License v3' : /zlib/i.test(file) ? 'zlib License' : /bsd/i.test(file) ? 'BSD License' : 'Licence');
for (const id of [...linked].sort()) {
  const p = pkgs.get(id)!;
  const dir = dirname(p.manifest_path);
  const files = p.license_file ? [p.license_file] : readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f));
  const crate = `${p.name} ${p.version}${p.license ? ` (${p.license})` : ''}`;
  if (!files.length) missing.push(crate);
  for (const f of files) {
    const path = join(dir, f);
    if (!existsSync(path)) continue;
    const text = readFileSync(path, 'utf8').trim();
    const e = texts.get(text) ?? { name: label(f), crates: [] };
    e.crates.push(crate);
    texts.set(text, e);
  }
}

const lines = [
  '# Third-party licences of the native natural voice',
  '',
  'The Android app\'s `libptts_ffi.so` is compiled from Gradium\'s xn-ptts (MIT OR Apache-2.0, see',
  '`xn-ptts.txt`), the Rust crates listed here and the Rust standard library, which is available under',
  'the MIT or Apache-2.0 licence (https://github.com/rust-lang/rust). Each distinct licence text is given',
  'once, with the crates it covers. Generated by `scripts/ptts/licenses.ts` from the pinned commit.',
  '',
];
if (missing.length) lines.push('Crates that ship no licence file (their licence as declared):', ...missing.map((m) => `- ${m}`), '');
for (const [text, e] of [...texts].sort((a, b) => a[1].name.localeCompare(b[1].name) || b[1].crates.length - a[1].crates.length)) {
  lines.push(`## ${e.name}`, '', 'Used by:', ...e.crates.map((c) => `- ${c}`), '', '```text', text, '```', '');
}
writeFileSync(out, lines.join('\n'));
console.log(`${linked.size} crates, ${texts.size} licence texts, ${missing.length} without a file -> ${out}`);
